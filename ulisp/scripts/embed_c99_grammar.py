#!/usr/bin/env python3
"""Embed tools/grammars/c99.peg into a deterministic ULisp Scheme module."""

import argparse
from pathlib import Path


def escape_scheme_string(text: str) -> str:
    """Escape text as an R7RS / ULisp double-quoted string literal."""
    out: list[str] = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        else:
            out.append(ch)
    return "".join(out)


def embed_grammar(input_path: Path, output_path: Path) -> None:
    """Read PEG grammar from input_path and emit Scheme registrar to output_path."""
    grammar_text = input_path.read_text(encoding="utf-8")
    escaped = escape_scheme_string(grammar_text)
    content = (
        ";;; Auto-generated by scripts/embed_c99_grammar.py — DO NOT EDIT\n"
        f'(c99-register-embedded-grammar! "{escaped}")\n'
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    if output_path.exists() and output_path.read_text(encoding="utf-8") == content:
        return
    output_path.write_text(content, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate build/c99_grammar_embedded.scm from tools/grammars/c99.peg"
    )
    parser.add_argument(
        "--input",
        default=str(Path(__file__).resolve().parents[2] / "tools/grammars/c99.peg"),
        help="Path to c99.peg",
    )
    parser.add_argument(
        "--output",
        default=str(
            Path(__file__).resolve().parents[1] / "build/c99_grammar_embedded.scm"
        ),
        help="Path to generated .scm file",
    )
    args = parser.parse_args()
    embed_grammar(Path(args.input), Path(args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
